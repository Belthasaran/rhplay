void gfx_route_build(LevelGfxRoute *out, const PrimaryLevelHeader *primary,
                     const uint8_t *exgfx_bytes, size_t exgfx_len) {
  if (!out) return;
  memset(out, 0, sizeof(*out));
  uint8_t tileset = primary ? (uint8_t)(primary->fgbg_gfx_setting & 0x0F) : 0;
  if (tileset >= 26) tileset = 0;
  uint32_t base = (uint32_t)tileset * 4u;
  for (int p = 0; p < 4; p++) {
    uint32_t idx = base + (uint32_t)p;
    out->file_id_for_page[p] = kFGAndBGGFXList[idx < 104 ? idx : 0];
  }
  // LM Super GFX bypass: first 4 bytes often override SP1/SP2/FG pages when non-zero.
  if (exgfx_bytes && exgfx_len >= 4) {
    for (int p = 0; p < 4; p++) {
      uint8_t b = exgfx_bytes[p];
      if (b != 0 && b != 0xFF) out->file_id_for_page[p] = (uint8_t)(b - 1);
    }
  }
  out->valid = 1;
}

uint8_t gfx_route_file_for_tile(const LevelGfxRoute *route, uint16_t tile8) {
  if (!route || !route->valid) {
    uint8_t page = (uint8_t)((tile8 >> 8) & 0x03);
    return (uint8_t)(0x00 + page);
  }
  uint8_t page = (uint8_t)((tile8 >> 8) & 0x03);
  return route->file_id_for_page[page];
}
